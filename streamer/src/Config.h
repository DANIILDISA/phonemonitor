#pragma once

/*
 * =============================================================================
 *  Конфигурация стримера и разбор командной строки.
 * =============================================================================
 *
 *  Значения по умолчанию подобраны под основной сценарий: телефон 1080p,
 *  подключённый по USB 2.0/3.0, кабель гарантирует не менее 25 Мбит/с.
 */

#include <windows.h>
#include <string>
#include <cstdint>

#include "pm_protocol.h"

namespace pm
{
    struct AppConfig
    {
        /* --- Сеть --------------------------------------------------------- */
        uint16_t port = PM_TCP_PORT;         /* порт по обе стороны форварда   */
        uint32_t connectTimeoutMs = 120000;  /* сколько ждать клиента          */

        /* --- ADB ----------------------------------------------------------- */
        std::wstring adbPath;                /* пусто - искать автоматически   */
        bool manageAdbForward = true;        /* --no-adb отключает управление  */
        uint32_t deviceWaitMs = 60000;       /* ожидание устройства            */

        /* --- Кодирование ---------------------------------------------------- */
        uint32_t bitrateBps = 15'000'000;    /* 15 Мбит/с по условию задачи    */
        uint32_t fps = 60;
        std::string encoderBackend = "auto"; /* auto | nvenc | mf              */
        uint32_t intraRefreshPercent = 5;    /* ширина полосы обновления, %    */
        bool intraRefresh = true;

        /* --- Тепловой режим -------------------------------------------------- */
        /* При THERMAL_STATUS_LIGHT и выше опускаем кодирование в 720p. */
        bool thermalMitigation = true;
        uint32_t thermalHeight = 720;
        uint32_t thermalBitrateBps = 6'000'000;

        /* --- Драйвер --------------------------------------------------------- */
        uint32_t driverWaitMs = 30000;       /* ожидание секции драйвера       */

        /* --- Диагностика ------------------------------------------------------ */
        bool verbose = false;                /* уровень TRACE                  */
        bool noColors = false;
        std::wstring logFilePath;
        uint32_t statsIntervalFrames = 300;  /* сводка раз в N кадров          */

        /* --- Прочее ------------------------------------------------------------ */
        bool autoReconnect = true;           /* переподключаться после разрыва */
    };

    /*
     * Разбор аргументов. Возвращает false, если нужно завершить работу
     * (запрошена справка или аргументы некорректны).
     */
    bool ParseCommandLine(int argc, wchar_t** argv, AppConfig& config) noexcept;

    /* Вывод справки по ключам. */
    void PrintUsage() noexcept;
}
