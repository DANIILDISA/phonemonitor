#pragma once

/*
 * =============================================================================
 *  Единая точка подключения системных заголовков драйвера.
 * =============================================================================
 *
 *  Этот файл ОБЯЗАН включаться первым в каждом заголовке и каждой единице
 *  трансляции драйвера. Причина не стилистическая, а вполне техническая:
 *  связка UMDF 2.x + IddCx требует строго определённого порядка включения,
 *  и нарушение его даёт ошибки, которые никак не связаны с их настоящей
 *  причиной.
 *
 *  Порядок и зачем каждый шаг:
 *
 *  1. WIN32_NO_STATUS + windows.h
 *     Обычно winnt.h сам определяет часть кодов STATUS_*. Но драйверу нужен
 *     ПОЛНЫЙ набор из ntstatus.h, а два набора конфликтуют предупреждениями
 *     о переопределении макросов. Штатное решение - подавить определения в
 *     winnt.h и сразу после него подключить ntstatus.h целиком.
 *
 *     Практическое следствие пропуска этого шага: макрос WAIT_OBJECT_0
 *     разворачивается в ((STATUS_WAIT_0) + 0), а сам STATUS_WAIT_0 оказывается
 *     необъявленным. Ошибка указывает на строку с WaitForMultipleObjects,
 *     хотя виноват порядок включения заголовков.
 *
 *  2. ntstatus.h - полный набор кодов NTSTATUS.
 *
 *  3. wudfwdm.h - режимно-нейтральные определения WDM для пользовательского
 *     режима. Должен идти до wdf.h.
 *
 *  4. wdf.h - сам фреймворк. Определяет макрос WDFAPI.
 *
 *  5. iddcx.h - расширение класса косвенных дисплеев. В его начале стоит
 *     проверка `#ifndef WDFAPI / #error Include WDF.H first`, а в
 *     IddCxFuncEnum.h - проверки IDDCX_VERSION_MAJOR и IDDCX_VERSION_MINOR.
 *     Обе версии передаются из CMake как определения компилятора.
 * =============================================================================
 */

/* Полный набор кодов NTSTATUS вместо урезанного из winnt.h. */
#ifndef WIN32_NO_STATUS
#define WIN32_NO_STATUS
#endif
#include <windows.h>
#undef WIN32_NO_STATUS
#include <ntstatus.h>

/* Цепочка WDF: порядок обязателен. */
#include <wudfwdm.h>
#include <wdf.h>

/* Расширение класса косвенных дисплеев. */
#include <iddcx.h>
